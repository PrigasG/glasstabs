test_that("browser: a cancelled append can be immediately replaced by the same ID", {
  skip_on_covr()
  skip_if_not_installed("shinytest2")
  withr::local_envvar(GLASSTABS_TEST_PKG_ROOT = normalizePath(test_path("..", "..")))
  app <- shinytest2::AppDriver$new(test_path("apps", "browser-interactions"),
                                  name = "final-reappend", height = 800, width = 1000)
  on.exit(app$stop(), add = TRUE)
  app$wait_for_idle()
  app$get_js("window.__oldRender=Shiny.renderDependenciesAsync;window.__releases=[];
    Shiny.renderDependenciesAsync=function(){return new Promise(function(resolve){window.__releases.push(resolve);});};true")
  app$set_inputs(modern_append_dep = "click", wait_ = FALSE)
  app$wait_for_js("window.__releases.length===1")
  app$set_inputs(modern_remove_dep = "click", wait_ = FALSE)
  app$wait_for_js("document.getElementById('modern_tabs-navbar')._gtPendingAppends.get('dep').cancelled")
  app$set_inputs(modern_append_dep = "click", wait_ = FALSE)
  app$wait_for_js("window.__releases.length===2")
  app$get_js("window.__releases[1]();true")
  app$wait_for_js("document.getElementById('modern_tabs-pane-dep')?.classList.contains('active')")
  app$get_js("window.__releases[0]();Shiny.renderDependenciesAsync=window.__oldRender;true")
  app$wait_for_idle()
  expect_true(app$get_js("document.querySelectorAll('#modern_tabs-tab-dep').length===1 &&
    document.querySelectorAll('#modern_tabs-pane-dep').length===1 &&
    document.getElementById('modern_tabs-pane-dep').classList.contains('active')"))
})

