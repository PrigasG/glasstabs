test_that("browser: persistent ordering and server-approved close requests", {
  skip_on_covr()
  skip_if_not_installed("shinytest2")
  withr::local_envvar(GLASSTABS_TEST_PKG_ROOT = normalizePath(test_path("..", "..")))
  app_dir <- test_path("..", "..", "inst", "examples", "final-features")
  if (!dir.exists(app_dir)) app_dir <- system.file("examples", "final-features", package = "glasstabs")
  expect_true(dir.exists(app_dir))
  app <- shinytest2::AppDriver$new(app_dir, name = "final-features", height = 900, width = 1100)
  on.exit(app$stop(), add = TRUE)
  app$wait_for_idle()
  app$wait_for_js("document.querySelector('#workspace-navbar')._gtTabsInit === true")
  app$get_js("document.getElementById('workspace-tab-report').focus(); true")
  expect_true(app$get_js("
    (function(){var r=document.getElementById('workspace-tab-report');
      r.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowLeft',altKey:true,shiftKey:true,bubbles:true}));
      var values=Array.from(document.querySelectorAll('#workspace-navbar > .gt-tab-link')).map(function(l){return l.getAttribute('data-value');});
      return values[0]==='report' && values[1]==='home' && document.getElementById('workspace-tab-home').classList.contains('active');})()
  "))
  expect_true(app$get_js("
    (function(){var k='glasstabs:order:v1:'+JSON.stringify([location.pathname,'final-features-example']);
      return JSON.parse(localStorage.getItem(k))[0]==='report';})()
  "))
  expect_true(app$get_js("(function(){var el=document.getElementById('allow_close'),text=el.nextElementSibling;return el && text && el.getBoundingClientRect().right <= text.getBoundingClientRect().left + 1;})()"))
  app$set_inputs(allow_close = FALSE)
  app$get_js("document.querySelector('#workspace-tab-report .gt-tab-close').click(); true")
  app$wait_for_idle()
  expect_true(app$get_js("document.getElementById('workspace-tab-report') !== null"))
  app$set_inputs(allow_close = TRUE)
  app$get_js("document.querySelector('#workspace-tab-report .gt-tab-close').click(); true")
  app$wait_for_js("document.getElementById('workspace-tab-report') === null")
  expect_true(app$get_js("document.getElementById('workspace-tab-home').classList.contains('active')"))
  app$set_inputs(enabled = FALSE, mode = "preview", fields = "rating")
  expect_equal(app$get_value(input = "enabled"), FALSE)
  expect_equal(app$get_value(input = "mode"), "preview")
  app$set_inputs(reset = "click")
  app$wait_for_idle()
  expect_equal(app$get_value(input = "enabled"), TRUE)
  expect_equal(app$get_value(input = "mode"), "edit")
})


